#!/usr/bin/env python3
"""Regenerates js/ka-embed.js from data/**/*.json so the site works when index.html is simply double-clicked
(no web server). Run this again whenever you edit anything in data/."""
import json, os
from pathlib import Path
root = Path(__file__).resolve().parent.parent
out = {}
for p in sorted((root / 'data').rglob('*.json')):
    out[p.relative_to(root).as_posix()] = json.loads(p.read_text(encoding='utf-8'))
(root / 'js' / 'ka-embed.js').write_text('/* generated by tools/embed-data.py */\nwindow.KA_EMBED=' + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + ';\n', encoding='utf-8')
print('embedded', len(out), 'files,', round(os.path.getsize(root / 'js' / 'ka-embed.js') / 1048576, 2), 'MB')
